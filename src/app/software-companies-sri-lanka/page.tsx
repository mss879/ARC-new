import { Metadata } from "next";
import SoftwareCompaniesContent from "./content";
import {
    GUIDE_YEAR,
    PAGE_DATES,
    PAGE_DESCRIPTION,
    PAGE_IMAGE_URL,
    PAGE_SOCIAL_TITLE,
    PAGE_TITLE,
    PAGE_URL,
    companiesInRenderOrder,
    companyCount,
    faqs,
    topBySriLankaHeadcount,
} from "./page-data";

export const metadata: Metadata = {
    title: PAGE_TITLE,
    description: PAGE_DESCRIPTION,
    openGraph: {
        title: PAGE_SOCIAL_TITLE,
        description: `An independent editorial review of ${companyCount} Sri Lankan software firms across enterprise, mid-market, and boutique tiers — pricing, specialties, and comparisons.`,
        url: PAGE_URL,
        siteName: "ARC AI",
        locale: "en_GB",
        type: "article",
        publishedTime: PAGE_DATES.published,
        modifiedTime: PAGE_DATES.modified,
        authors: ["https://www.arcai.agency/about"],
        // og:image is generated by ./opengraph-image.tsx at a true 1200×630.
    },
    twitter: {
        card: "summary_large_image",
        site: "@arc_ai_agency",
        creator: "@arc_ai_agency",
        title: PAGE_SOCIAL_TITLE,
        description: `An independent editorial review of ${companyCount} Sri Lankan software firms — pricing, specialties, and comparisons.`,
        images: [PAGE_IMAGE_URL],
    },
    alternates: {
        canonical: PAGE_URL,
    },
    /* No page-level `robots` on purpose: the root layout's rule then applies in full,
     * including max-image-preview:large and max-snippet:-1 for Googlebot. Setting
     * `robots` here would replace that rule and drop both. */
    other: {
        // The root layout declares GB / Birmingham site-wide; this page is about Sri Lanka.
        "geo.region": "LK",
        "geo.placename": "Colombo, Sri Lanka",
    },
};

/* ── Structured Data — generated from page-data.ts so schema always matches the visible page ── */

const faqJsonLd = {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faqs.map((faq) => ({
        "@type": "Question",
        name: faq.q,
        acceptedAnswer: {
            "@type": "Answer",
            text: faq.a,
        },
    })),
};

const articleJsonLd = {
    "@context": "https://schema.org",
    "@type": "Article",
    "@id": `${PAGE_URL}#article`,
    headline: PAGE_TITLE,
    description: PAGE_DESCRIPTION,
    inLanguage: "en",
    image: {
        "@type": "ImageObject",
        url: PAGE_IMAGE_URL,
        width: 1200,
        height: 630,
    },
    author: {
        "@type": "Person",
        name: "Shahid Shamir",
        url: "https://www.arcai.agency/about",
        jobTitle: "Founder & Lead Engineer",
        worksFor: {
            "@type": "Organization",
            "@id": "https://www.arcai.agency/#organization",
            name: "ARC AI",
            url: "https://www.arcai.agency",
        },
        knowsAbout: ["Software development", "AI automation", "Sri Lanka IT industry"],
        sameAs: [
            "https://www.linkedin.com/in/shahid-shamir-2ab901105/",
        ],
    },
    publisher: {
        "@type": "Organization",
        // Same @id the site-wide Organization schema uses, so the two resolve to one entity.
        "@id": "https://www.arcai.agency/#organization",
        name: "ARC AI",
        url: "https://www.arcai.agency",
        logo: {
            "@type": "ImageObject",
            url: "https://www.arcai.agency/logo.png",
        },
        sameAs: [
            "https://www.linkedin.com/company/105845719",
        ],
    },
    datePublished: PAGE_DATES.published,
    dateModified: PAGE_DATES.modified,
    about: {
        "@type": "Thing",
        name: "Software industry in Sri Lanka",
    },
    mainEntityOfPage: {
        "@type": "WebPage",
        "@id": PAGE_URL,
    },
};

/* The page groups companies by size and says the order is not a ranking, so the list
 * is unordered and mirrors the on-page render order. Each company is an Organization
 * whose @id is its anchor on this page. */
const itemListJsonLd = {
    "@context": "https://schema.org",
    "@type": "ItemList",
    "@id": `${PAGE_URL}#companies`,
    name: `Software companies in Sri Lanka (${GUIDE_YEAR})`,
    numberOfItems: companiesInRenderOrder.length,
    itemListOrder: "https://schema.org/ItemListUnordered",
    itemListElement: companiesInRenderOrder.map((company, index) => ({
        "@type": "ListItem",
        position: index + 1,
        item: {
            "@type": "Organization",
            "@id": `${PAGE_URL}#${company.slug}`,
            name: company.name,
            url: company.website,
            description: company.tagline,
            foundingDate: company.founded,
            address: {
                "@type": "PostalAddress",
                addressLocality: company.city,
                addressCountry: "LK",
            },
        },
    })),
};

/* The one ordered list on the page: biggest employers by published Sri Lanka headcount.
 * Items point at the same Organization @ids as the main list. */
const topTenJsonLd =
    topBySriLankaHeadcount.length >= 5
        ? {
              "@context": "https://schema.org",
              "@type": "ItemList",
              "@id": `${PAGE_URL}#biggest`,
              name: `Biggest software companies in Sri Lanka by local headcount`,
              numberOfItems: topBySriLankaHeadcount.length,
              itemListOrder: "https://schema.org/ItemListOrderDescending",
              itemListElement: topBySriLankaHeadcount.map((company, index) => ({
                  "@type": "ListItem",
                  position: index + 1,
                  name: company.name,
                  item: { "@id": `${PAGE_URL}#${company.slug}` },
              })),
          }
        : null;

/* Breadcrumb markup is emitted once, as microdata, by the shared <Breadcrumbs>
 * component. A second JSON-LD copy used to live here and duplicated it.
 * Organization and LocalBusiness schemas belong on /about, not an editorial guide. */

export default function Page() {
    return (
        <>
            <script
                type="application/ld+json"
                dangerouslySetInnerHTML={{ __html: JSON.stringify(articleJsonLd) }}
            />
            <script
                type="application/ld+json"
                dangerouslySetInnerHTML={{ __html: JSON.stringify(itemListJsonLd) }}
            />
            {topTenJsonLd && (
                <script
                    type="application/ld+json"
                    dangerouslySetInnerHTML={{ __html: JSON.stringify(topTenJsonLd) }}
                />
            )}
            <script
                type="application/ld+json"
                dangerouslySetInnerHTML={{ __html: JSON.stringify(faqJsonLd) }}
            />
            <SoftwareCompaniesContent />
        </>
    );
}
